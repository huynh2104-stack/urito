/** 社内JAN（プレフィックス20）を検証桁付きEAN-13で生成する。 */
function jan20(index: number): string {
  const first12 = `20${String(index).padStart(10, '0')}`;
  return `${first12}${ean13CheckDigit(first12)}`;
}

